/**
 * Test script to verify V3 accessibility metadata completeness
 *
 * This script makes a request to the facilitator and validates that
 * ALL fields in the V3 accessibility metadata are populated with
 * AI-generated content specific to the transaction.
 */

const FACILITATOR_URL = 'http://localhost:8787';

// Sample transaction for testing
const SAMPLE_TRANSACTION = '0100000001f292fd5e700f44841e042492...' // Truncated for brevity

async function testV3Completeness() {
  console.log('🧪 Testing V3 Accessibility Metadata Completeness\n');

  try {
    // Test 1: Verify endpoint
    console.log('📋 Test 1: POST /verify with V3 preferences');
    const verifyResponse = await fetch(`${FACILITATOR_URL}/verify`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Accept-Language': 'es',
        'X-Accessibility-Preferences': JSON.stringify({
          cognitiveLevel: 'simple',
          contrastMode: 'high',
          motorInput: 'keyboard',
          languages: ['es', 'en'],
          primaryLanguage: 'es',
        })
      },
      body: JSON.stringify({
        transaction: SAMPLE_TRANSACTION,
        paymentRequirements: {
          network: 'mainnet',
          payTo: [{
            address: '1A1zP1eP5QGefi2DMPTfTL5SLmv7DivfNa',
            amount: '1000'
          }]
        }
      })
    });

    if (!verifyResponse.ok) {
      const error = await verifyResponse.text();
      console.error('❌ Request failed:', error);
      return;
    }

    const data = await verifyResponse.json();
    console.log('✅ Response received\n');

    // Validate V3 structure
    if (!data.accessibility || data.accessibility.metadata?.version !== 3) {
      console.error('❌ Not a V3 response');
      return;
    }

    const accessibility = data.accessibility;
    console.log('📊 Metadata Version:', accessibility.metadata.version);
    console.log('🤖 Generated By:', accessibility.metadata.generatedBy);
    console.log('💾 Cache Hit:', accessibility.metadata.cacheHit);
    console.log('');

    // Validate content section
    validateContentSection(accessibility.content);

    // Validate languages section
    validateLanguagesSection(accessibility.languages);

    // Validate visual section
    validateVisualSection(accessibility.visual);

    // Validate motor section
    validateMotorSection(accessibility.motor);

    // Validate audio section
    validateAudioSection(accessibility.audio);

    // Validate formats section
    validateFormatsSection(accessibility.formats);

    console.log('\n✅ ALL VALIDATIONS PASSED - V3 metadata is COMPLETE\n');

  } catch (error) {
    console.error('❌ Test failed:', error.message);
    process.exit(1);
  }
}

function validateContentSection(content) {
  console.log('🧠 Validating Content Section (Cognitive Levels)');

  const levels = ['beginner', 'simple', 'medium', 'advanced', 'expert'];
  for (const level of levels) {
    if (!content.byLevel[level]) {
      throw new Error(`Missing cognitive level: ${level}`);
    }

    const cogContent = content.byLevel[level];

    // Validate required fields
    const requiredFields = [
      'plainLanguage',
      'explanation',
      'stepByStep',
      'hints',
      'glossary',
      'examples',
      'checkpoints',
      'memoryAids'
    ];

    for (const field of requiredFields) {
      if (!cogContent[field]) {
        throw new Error(`Missing field '${field}' in level '${level}'`);
      }

      // Validate arrays are NOT empty
      if (Array.isArray(cogContent[field]) && cogContent[field].length === 0) {
        throw new Error(`Empty array '${field}' in level '${level}'`);
      }

      // Validate objects are NOT empty
      if (typeof cogContent[field] === 'object' && !Array.isArray(cogContent[field])) {
        if (field === 'glossary' && Object.keys(cogContent[field]).length === 0) {
          throw new Error(`Empty glossary in level '${level}'`);
        }
        if (field === 'hints') {
          if (!cogContent[field].ifError || !cogContent[field].nextSteps) {
            throw new Error(`Missing hints.ifError or hints.nextSteps in level '${level}'`);
          }
          if (!cogContent[field].commonMistakes || cogContent[field].commonMistakes.length === 0) {
            throw new Error(`Empty commonMistakes in level '${level}'`);
          }
        }
      }
    }

    console.log(`  ✅ ${level}: All fields populated`);
  }
  console.log('');
}

function validateLanguagesSection(languages) {
  console.log('🌐 Validating Languages Section');

  const requiredLangs = ['es', 'en'];
  for (const lang of requiredLangs) {
    if (!languages[lang]) {
      throw new Error(`Missing language: ${lang}`);
    }

    const langContent = languages[lang];
    if (!langContent.byLevel || !langContent.byAbstraction) {
      throw new Error(`Incomplete content for language: ${lang}`);
    }

    console.log(`  ✅ ${lang}: Complete`);
  }
  console.log('');
}

function validateVisualSection(visual) {
  console.log('👁️  Validating Visual Section');

  if (!visual.contrast || !visual.colorBlind || !visual.fontSize || !visual.theme) {
    throw new Error('Missing visual properties');
  }

  console.log(`  ✅ Contrast modes: ${Object.keys(visual.contrast).length}`);
  console.log(`  ✅ ColorBlind modes: ${Object.keys(visual.colorBlind).length}`);
  console.log(`  ✅ Font sizes: ${Object.keys(visual.fontSize).length}`);
  console.log(`  ✅ Themes: ${Object.keys(visual.theme).length}`);
  console.log('');
}

function validateMotorSection(motor) {
  console.log('⌨️  Validating Motor Section');

  const requiredModes = ['keyboard', 'voice', 'switch', 'eye'];
  for (const mode of requiredModes) {
    if (!motor[mode]) {
      throw new Error(`Missing motor mode: ${mode}`);
    }
    if (!motor[mode].instructions || motor[mode].instructions.length === 0) {
      throw new Error(`Empty instructions for motor mode: ${mode}`);
    }
    console.log(`  ✅ ${mode}: ${motor[mode].instructions.length} instructions`);
  }
  console.log('');
}

function validateAudioSection(audio) {
  console.log('🔊 Validating Audio Section');

  const requiredModes = ['ttsOptimized', 'ttsNonOptimized', 'withPauses', 'withoutPauses'];
  for (const mode of requiredModes) {
    if (!audio[mode]) {
      throw new Error(`Missing audio mode: ${mode}`);
    }
    if (!audio[mode].text) {
      throw new Error(`Missing text for audio mode: ${mode}`);
    }
    console.log(`  ✅ ${mode}: Present`);
  }
  console.log('');
}

function validateFormatsSection(formats) {
  console.log('📄 Validating Formats Section');

  const requiredFormats = ['json', 'xml', 'plaintext', 'markdown', 'html', 'jsonld', 'braille', 'ssml'];
  for (const format of requiredFormats) {
    if (!formats[format]) {
      throw new Error(`Missing format: ${format}`);
    }
    console.log(`  ✅ ${format}: Present`);
  }
  console.log('');
}

// Run tests
testV3Completeness();
